// Lists the clips in public/clips so a scene can fall back to a still when its
// recording is not there yet: CLIPS.includes(name) → video, otherwise Img.
import { readdirSync, mkdirSync, writeFileSync } from "node:fs";

mkdirSync("public/clips", { recursive: true });
const clips = readdirSync("public/clips")
  .filter((f) => f.endsWith(".mp4"))
  .map((f) => f.replace(/\.mp4$/, ""))
  .sort();
writeFileSync(
  "src/clips.generated.ts",
  `// Generated by scripts/sync-clips.mjs — do not edit.\nexport const CLIPS: string[] = ${JSON.stringify(clips)};\n`,
);
console.log("clips:", clips.join(", ") || "none");
